def swap(word, sign):
    """[word] with its last vowel made [sign]: a vowel sign replaced, the inherent a or a final ం (as మ) taking it."""
    if word.endswith(ANUSVARA):
        return word[:-1] + "మ" + sign
    if word[-1] in SIGNS:
        return word[:-1] + sign
    if word[-1] in CONSONANTS:
        return word + sign
    return word + sign


def clitic_signs(word):
    """The clitic vowels [word] may end in: ఏ and ఆ, and ఊ after u (ఇల్లూ), ఈ after i (అదీ)."""
    if word.endswith("\u0c41"):
        return ["\u0c47", "\u0c3e", "\u0c42"]
    if word.endswith("\u0c3f"):
        return ["\u0c47", "\u0c3e", "\u0c40"]
    return ["\u0c47", "\u0c3e"]


def both_l(forms):
    """Forms with ళ్ళ written as ళ్ల too, and the other way round: texts write both."""
    out = set(forms)
    for f in forms:
        if "ళ్ళ" in f:
            out.add(f.replace("ళ్ళ", "ళ్ల"))
        if "ళ్ల" in f:
            out.add(f.replace("ళ్ల", "ళ్ళ"))
    return out


def modern(word):
    """The spelling texts write a word in: the old ఱ as ర (మాఱు, మారు), without the old half nasal ఁ (వాఁడు), and the old -ము of a noun as -ం (పుస్తకము, పుస్తకం)."""
    word = word.replace("ఱ", "ర").replace("ఁ", "").replace("ౙ", "జ").replace("ౘ", "చ")
    if word.endswith("ము") and len(word) > 3 and word[-3] in CONSONANTS:
        return word[:-2] + ANUSVARA
    return word


