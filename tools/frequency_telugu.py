def _sentences(dictionaries, corpora):
    """Each sentence of the Leipzig archives [corpora] as (its page, its tokens: each a Telugu word, "latin" or "", and
    whether a stop or comma ends it)."""
    for corpus in corpora:
        path = os.path.join(dictionaries, "frequency-sources", f"leipzig-{corpus}.tar.gz")
        if not os.path.exists(path):
            continue
        with tarfile.open(path) as tar:
            members = {m.name.rsplit("-", 1)[-1]: m for m in tar.getmembers() if m.isfile()}
            page_of = {}
            for line in io.TextIOWrapper(tar.extractfile(members["inv_so.txt"]), encoding="utf-8"):
                source, sentence = line.rstrip("\n").split("\t")[:2]
                page_of[sentence] = source
            for line in io.TextIOWrapper(tar.extractfile(members["sentences.txt"]), encoding="utf-8"):
                number, _, text = line.rstrip("\n").partition("\t")
                tokens = []
                for raw in unicodedata.normalize("NFC", text).split():
                    bare = EDGE.sub("", raw)
                    if DOTTED.fullmatch(raw):
                        tokens.append(("initial", False))
                        continue
                    if TELUGU_LETTERS.fullmatch(bare) and not STRAY_JOINER.search(bare):
                        word = bare
                    else:
                        word = "latin" if LATIN.search(bare) else ""
                    tokens.append((word, bool(BREAK.search(raw))))
                yield corpus + "/" + page_of.get(number, ""), tokens


def read_usage(dictionaries, corpora, known):
    """
    How often the sentences of [corpora] have each Telugu form (seen), counting each page PAGE_MOST times at most (spread),
    and how often as a name's piece or in English (lost), [known] being the forms a word of the list explains.
    """
    sentences = sorted(_sentences(dictionaries, corpora), key=lambda s: s[0])
    seen = Counter()
    for _, tokens in sentences:
        seen.update(w for w, _ in tokens if w and w not in ("latin", "initial"))

    def foreign(word):
        return word == "latin" or (word.endswith(VIRAMA) and word not in known)

    spread, lost, pairs = Counter(), Counter(), Counter()
    page, on_page = None, Counter()
    for here, tokens in sentences + [(None, [])]:
        if here != page:
            spread.update({w: min(n, PAGE_MOST) for w, n in on_page.items()})
            page, on_page = here, Counter()
        last = len(tokens) - 1
        for i, (word, stop) in enumerate(tokens):
            if not word or word in ("latin", "initial"):
                continue
            on_page[word] += 1
            before = tokens[i - 1][0] if i and not tokens[i - 1][1] else ""
            after = tokens[i + 1][0] if i < last and not stop else ""
            loan = word.endswith(VIRAMA) and any(n == "latin" or n.endswith(VIRAMA) for n in (before, after) if n)
            if (before in TITLES or before in INITIALS or before == "initial" or after in NAME_PARTS or foreign(before)
                    or foreign(after) or loan):
                lost[word] += 1
            if after and after not in ("latin", "initial") and word + after in known:
                pairs[word, after] += 1
    # Two pieces of a word the sentences write whole at least as often as apart (ఆసక్తి కరంగా, ప్రభుత్వ పరంగా).
    for (a, b), n in sorted(pairs.items()):
        if seen[a + b] >= n:
            lost[a] += n
            lost[b] += n
    return seen, spread, lost


def build(found, size, label, weights=None):
    """The list: the words of the pack and TELUGU_WORDS, by their forms' counts in [found] ((name, counts, label) each), the
    sources weighted by [weights] (name -> share) or alike."""
    dictionaries = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "dictionaries")
    kinds, pack_forms, names, spellings, named = lexicon(dictionaries)
    weights = weights or {}
    share_of = {name: weights.get(name, 1 / len(found)) for name, _, _ in found}
    scale = sum(share_of.values())
    counts = defaultdict(float)
    by_source = defaultdict(lambda: defaultdict(float))
    raw = defaultdict(int)
    for name, source, _ in found:
        total = sum(source.values())
        for form, n in source.items():
            # A vowel written in two parts (ె + ౖ for ై) is the one letter.
            form = unicodedata.normalize("NFC", form)
            if TELUGU_LETTERS.fullmatch(form) and not STRAY_JOINER.search(form):
                counts[form] += n / total * share_of[name] / scale
                by_source[name][form] += n / total * share_of[name] / scale
                raw[form] += n

    alias = dict(TELUGU_SPELLINGS)
    # An adverb or adjective of a noun the pack lacks (ఇతివృత్తంగా, ఇతివృత్తమైన, నేర్పుగా) is that noun's, when the corpus
    # writes it.
    # One in -ుగా (నేర్పుగా, నిజముగా) is so only after a noun in -u, the old -ము being -ం (నిజం); తిన్నగా "straight" is no
    # తిన్న's.
    for word in sorted(kinds):
        for tail in ("ంగా", "మైన", "ుగా"):
            if tail == "ుగా" and kinds[word] != {"adv"}:
                continue
            noun = modern(word[:-len(tail)] + ("\u0c41" if tail == "ుగా" else ANUSVARA))
            if (not word.endswith(tail) or not kinds[word] <= {"adv", "adj", "noun"} or word in TELUGU_WORDS
                    or len(noun) < 4):
                continue
            if noun in kinds:
                alias[word] = noun
                kinds.pop(word)
            elif counts.get(noun, 0) > 0:
                kinds[noun] = {"noun"}
                kinds.pop(word)
            break
    # A noun the pack writes in -ము that texts decline in -a (పాలన, పాలనలో; not పాలనం, పాలనంలో) is listed in -a.
    for word in [w for w in kinds if w.endswith(ANUSVARA) and w not in TELUGU_WORDS and w[:-1] not in kinds]:
        stem = word[:-1]
        as_a = sum(counts.get(stem + t, 0) for t in ("లో", "ను", "కు", "లు", "తో", "ల", "కి", "ని"))
        as_am = sum(counts.get(f, 0) for f in (word + "లో", stem + "ాన్ని", stem + "ానికి", stem + "ాలు", word + "తో", stem + "ాల"))
        if as_a > 2 * as_am and as_a > counts.get(word, 0) / 5:
            kinds[stem] = kinds.pop(word)
            alias[word] = stem

    by_hand = defaultdict(set)
    for word, (_, forms) in TELUGU_WORDS.items():
        for form in forms.split():
            by_hand[form].add(word)
    for form, word in TELUGU_FORMS.items():
        by_hand[form].add(word)
    for spelling, word in alias.items():
        by_hand[spelling].add(word)

    # A reflexive with కొను on a word the pack has no verb for (ఒప్పుకున్నారు, కోలుకున్నారు, పుంజుకుంది) is a verb of its own
    # (ఒప్పుకొను), when the corpus writes KONU_LEAST of its forms, one of them no dative with ఉండు (ఎందుకున్నారు is ఎందుకు
    # ఉన్నారు).
    konu = defaultdict(set)
    for form in counts:
        for tail in KONU_TAILS:
            lead = form[:-len(tail)]
            if form.endswith(tail) and len(lead) > 2 and lead.endswith("\u0c41") and lead in kinds and "verb" not in kinds[lead]:
                konu[lead + "కొను"].add(tail)
    for verb, tails in sorted(konu.items()):
        if len(tails) >= KONU_LEAST and verb not in kinds and any(t.startswith(("కోవ", "కోల", "కోం", "కోక", "కోగ", "కోబ", "కుని", "కొని")) for t in tails):
            kinds[verb] = {"verb"}

    needed = set(counts)
    for form in counts:
        needed |= unclitic(form)
    ruled = defaultdict(set)
    for word, ks in kinds.items():
        for form in word_forms(word, ks):
            if form in needed:
                ruled[form].add(word)
    for form, words in pack_forms.items():
        if form in needed:
            ruled[form] |= {w for w in words if w in kinds}
    # A word's other spelling is declined as it is (మర్చిపోతే of మరచిపోవు, by మర్చిపోవు).
    for spelling, word in alias.items():
        if word in kinds:
            for form in word_forms(spelling, kinds[word]) | {spelling}:
                if form in needed:
                    ruled[form].add(word)

    # A word of the pack that is a verb's form (ఉండి, చెప్పిన, రావడం) or an adverb or adjective of a noun (పూర్తిగా, అందమైన)
    # is that word's form, unless TELUGU_OWN keeps it.
    folded = set()
    for word in list(kinds):
        if word in TELUGU_WORDS or word in TELUGU_OWN:
            continue
        others = ruled.get(word, set()) - {word}
        if others and word.endswith(FOLDED_ENDINGS[kind_of(kinds[word]) if kinds[word] & {"noun", "verb", "adj"} else "adv"]) and (
                any("verb" in kinds[o] for o in others) or word.endswith(("గా", "మైన"))):
            folded.add(word)
    for word in folded:
        kinds.pop(word)
    if folded:
        for form in ruled:
            ruled[form] -= folded
    # A noun of the pack given in the plural or the plural's oblique of another the rules decline (ముత్యాలు of ముత్యం, చుక్కల of
    # చుక్క, కోళ్ళు of కోడి) is that one's, when the corpus writes that one too.
    plurals = {}
    for word in sorted(kinds):
        if word in TELUGU_WORDS or word in TELUGU_OWN or not kinds[word] <= {"noun", "adj"} or not word.endswith(("లు", "ల")):
            continue
        heads = {h for h in ruled.get(word, ()) if h != word and kinds.get(h, set()) & {"noun", "num"} and counts.get(h, 0) > 0
                 and (word.endswith("లు") or counts.get(h, 0) > counts.get(word, 0))}
        if heads:
            plurals[word] = heads
    for word, heads in plurals.items():
        kinds.pop(word)
        by_hand[word] |= heads
    for form in ruled:
        ruled[form] -= set(plurals)
    for form, heads in ruled.items():
        if len(heads) < 2:
            continue
        # A form of a verb in -కొను is that verb's (తీసుకున్నారు of తీసుకొను, not తీయు's compound).
        reflexive = {h for h in heads if h.endswith("కొను") and form in simple_verb_forms(h)}
        if reflexive:
            heads &= reflexive
        # A plural in -ులు is the noun's in -ు (మందులు of మందు), not the one in -ి's (మంది).
        heads -= {h for h in heads if h.endswith("\u0c3f") and (h[:-1] + "\u0c41" in heads or h[:-1] in heads)
                  and form.startswith((h[:-1] + "\u0c41ల", h[:-1] + "ల"))}
        # A verb in -యు's present is not one in -చు's (వేస్తున్నారు of వేయు, not వేచు).
        heads -= {h for h in heads if h.endswith("చు") and h[:-2] + "యు" in heads}

    def plain_targets(form):
        if form in by_hand:
            return by_hand[form]
        if form in kinds:
            return {form}
        return ruled.get(form, set())

    by_clitic = set()

    def targets(form):
        if form in TELUGU_EXCLUDED:
            return set()
        heads = plain_targets(form)
        if not heads and form not in names:
            for base in clitic_bases(form, kinds):
                heads = heads | plain_targets(base)
            if heads:
                by_clitic.add(form)
        if not heads and form not in names:
            for lead in light_split(form):
                # A past participle with పోవు or వేయు is its verb's (మారిపోతూ of మారు).
                verb = lead[:-1] + "\u0c41" if lead.endswith("\u0c3f") and form[len(lead):] in after_participle() else None
                if verb and "verb" in kinds.get(verb, ()):
                    return {verb}
                if kinds.get(lead, set()) & {"noun", "adj"} and lead not in LIGHT_NOT:
                    return {lead}
        return heads

    found_targets = {form: targets(form) for form in counts}
    # The news's and Wikipedia's counts are their uses spread over the pages and as no name's piece (read_usage).
    known = {f for f, heads in found_targets.items() if heads}
    usage = {name: read_usage(dictionaries, corpora, known) for name, corpora in sorted(TELUGU_CORPORA.items())
             if name in by_source}
    for name, (seen, spread, lost) in sorted(usage.items()):
        for form, share in by_source[name].items():
            if seen[form]:
                counts[form] -= share * (1 - spread[form] / seen[form] * (1 - min(lost[form], seen[form]) / seen[form]))

    # A form of several words is shared by how common each is by its forms of no other word.
    own = defaultdict(float)
    for form, share in counts.items():
        heads = found_targets[form]
        if len(heads) == 1:
            own[next(iter(heads))] += share
    scores = defaultdict(float)
    uses = defaultdict(float)
    forms = defaultdict(dict)
    for form, share in counts.items():
        heads = sorted(found_targets[form])
        if not heads:
            continue
        weights_here = {h: own.get(h, 0.0) for h in heads}
        whole = sum(weights_here.values())
        for head in heads:
            part = weights_here[head] / whole if whole else 1 / len(heads)
            if part <= 0:
                continue
            scores[head] += share * part
            uses[head] += raw.get(form, 0) * part
            forms[head][form] = forms[head].get(form, 0.0) + share * part

    # A word's forms with a clitic count at most as much as its others: a word written mostly so is a name or another's piece
    # (రోసీ, రోసా are no forms of రోయు).
    for word in sorted(scores):
        if word in TELUGU_WORDS:
            continue
        clitic = sum(share for f, share in forms[word].items() if f in by_clitic)
        if clitic > scores[word] - clitic:
            for f in [f for f in forms[word] if f in by_clitic]:
                forms[word][f] *= (scores[word] - clitic) / clitic
            scores[word] = 2 * (scores[word] - clitic)

    # Two spellings of a verb are one word, under the commoner.
    for form, lemma in spellings.items():
        if form in scores and lemma in scores:
            head, other = (form, lemma) if scores[form] > scores[lemma] else (lemma, form)
            scores[head] += scores.pop(other)
            uses[head] += uses.pop(other, 0.0)
            for f, share in forms.pop(other).items():
                forms[head][f] = forms[head].get(f, 0.0) + share

    # A noun the pack has as a person's or place's name too (named), or that the sentences mostly use as a name's piece
    # (NAMED_SHARE), is a name.
    for word in sorted(scores):
        if word in named:
            del scores[word]
            continue
        if word in TELUGU_WORDS or not kinds.get(word, {"noun"}) <= {"noun", "adj"}:
            continue
        seen_here = sum(u[0][f] for u in usage.values() for f in forms[word])
        lost_here = sum(min(u[2][f], u[0][f]) for u in usage.values() for f in forms[word])
        if seen_here >= NAMED_LEAST and lost_here >= NAMED_SHARE * seen_here:
            del scores[word]

    # A word is listed when its forms are written LEAST_COUNT times in all the sources (one use in the small subtitles weighs
    # as much as twenty in the news).
    ranked = [w for w in sorted(scores, key=lambda w: (-scores[w], w)) if uses[w] >= LEAST_COUNT][:size]
    lines = [f"# source: {label}", f"# words: {len(ranked)}"]
    for word in ranked:
        listed = sorted(forms[word], key=lambda f: (-forms[word][f], f))[:FORMS_LISTED]
        if word not in listed:
            listed = [word] + listed[:FORMS_LISTED - 1]
        lines.append(word + "\t" + " ".join(listed))
    return "\n".join(lines) + "\n", label


# The checker (check_course.py) reads a word the pinned list does not have by these rules: చేస్తున్నాను is చేయు's, ఇంటికి
# ఇల్లు's and రాముడికి the name రాముడు's.
_CHECKER_INDEX = {}


def _checker_kinds(word, listed):
    """A listed word's kinds as the rules decline it: a verb when its listed forms are a verb's, a noun too."""
    hand = TELUGU_WORDS.get(word)
    if hand and hand[0] not in ("noun", "adj", "verb"):
        return {hand[0]}
    ks = {"noun", "adj"}
    if word in IRREGULAR_VERBS or (hand and hand[0] == "verb") or (
            verb_stems(word) is not None and set(listed) & (simple_verb_forms(word) - {word})):
        ks.add("verb")
    return ks


@functools.lru_cache(maxsize=None)
def _rule_forms(word, kinds):
    return frozenset(word_forms(word, set(kinds))) | {word}


@functools.lru_cache(maxsize=None)
def _name_forms(name):
    """A name's case forms: a noun's (రాముడికి, సీతకు, హైదరాబాద్‌లో)."""
    return _rule_forms(name, frozenset({"noun"}))


def checker_word(token, words, ranks, names=frozenset()):
    """
    The list's word [token] is a form of by the rules, as a key of [words] (the checker's list: key -> (rank, word, forms)),
    the commonest when it may be several; "\\0name" when it is a case form of one of the course's [names]; or None.
    A form with a clitic (అదే, ఇప్పుడే, ఉందని) is read as the form without it.
    """
    for base in sorted(unclitic(token)):
        if base in ranks:
            return base
    index = _CHECKER_INDEX.get(id(words))
    if index is None:
        index = defaultdict(set)
        for key, (_, _, listed) in words.items():
            kinds = frozenset(_checker_kinds(key, listed))
            for start in {key[:2], key[:1]}:
                index[start].add((key, kinds))
        _CHECKER_INDEX.clear()
        _CHECKER_INDEX[id(words)] = index
    candidates = {token} | unclitic(token)
    for name in names:
        if name.startswith("\u0000"):
            continue
        if any(c.startswith(name[:2]) for c in candidates) and candidates & _name_forms(name):
            return "\u0000name"
    found = []
    for start in {token[:2], token[:1]}:
        for key, kinds in index.get(start, ()):
            if candidates & _rule_forms(key, kinds):
                found.append((words[key][0], key))
    if found:
        return min(found)[1]
    for lead in light_split(token):
        if lead in words:
            return lead
    return None
