#!/usr/bin/env python3
"""
Generates core/domain/.../morphology/UnicodeTables.kt, the data Unicode.kt needs for canonical
normalisation (NFD and NFC), which Kotlin's common library lacks: every BMP character's canonical
decomposition (one level), the characters that compose back (not excluded from composition) and
the combining classes of the characters that have one. Hangul syllables are decomposed by rule.

Usage: python3 tools/generate_unicode_tables.py
"""
import sys
import unicodedata

OUT = "core/domain/src/commonMain/kotlin/com/tayra/languages/core/domain/morphology/UnicodeTables.kt"


def kotlin_string(text):
    out = []
    for c in text:
        code = ord(c)
        if c in '\\"$' or code < 0x20 or 0xD800 <= code <= 0xDFFF or code >= 0x7F:
            out.append(f"\\u{code:04x}")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'


def chunks(text, size=6000):
    return [text[i:i + size] for i in range(0, len(text), size)]


def main():
    decompositions = []
    composable = []
    classes = []
    for code in range(0x10000):
        if 0xD800 <= code <= 0xDFFF or 0xAC00 <= code <= 0xD7A3:
            continue
        c = chr(code)
        raw = unicodedata.decomposition(c)
        if raw and not raw.startswith("<"):
            parts = "".join(chr(int(x, 16)) for x in raw.split())
            if all(ord(p) < 0x10000 for p in parts):
                decompositions.append(c + chr(len(parts)) + parts)
                if len(parts) == 2 and unicodedata.normalize("NFC", parts) == c:
                    composable.append(c)
        ccc = unicodedata.combining(c)
        if ccc:
            classes.append(c + chr(ccc))
    lines = [
        "package com.tayra.languages.core.domain.morphology",
        "",
        f"// Generated by tools/generate_unicode_tables.py from Unicode {unicodedata.unidata_version}. Do not edit by hand.",
        "",
        "/** Each decomposable character, the length of its canonical decomposition and the decomposition. */",
        "internal val unicodeDecompositions: String = listOf(",
        *[f"    {kotlin_string(part)}," for part in chunks("".join(decompositions))],
        ").joinToString(\"\")",
        "",
        "/** The characters whose two-character decomposition composes back under NFC. */",
        "internal val unicodeComposable: String = listOf(",
        *[f"    {kotlin_string(part)}," for part in chunks("".join(composable))],
        ").joinToString(\"\")",
        "",
        "/** Each character with a combining class, followed by the class as a character. */",
        "internal val unicodeCombiningClasses: String = listOf(",
        *[f"    {kotlin_string(part)}," for part in chunks("".join(classes))],
        ").joinToString(\"\")",
        "",
    ]
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {OUT}: {len(decompositions)} decompositions, {len(composable)} composable, {len(classes)} combining classes", file=sys.stderr)


if __name__ == "__main__":
    main()
