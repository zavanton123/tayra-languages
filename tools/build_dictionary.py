def pashto_translation_entries(kept):
    """
    The Pashto words the English Wiktionary's translation tables give that its Pashto entries lack (it has 1,600 entries,
    its tables 4,000 Pashto words), by part of speech, each glossed with the English words it translates: word -> pos -> glosses.
    """
    entries = defaultdict(lambda: defaultdict(list))
    with open_text(SOURCES["en"][2]) as f:
        for line in f:
            if '"code": "ps"' not in line:
                continue
            d = json.loads(line)
            # The tables are the entry's, or (most) a sense's, which glosses the English word where the table does not.
            tables = [(t, None) for t in d.get("translations", [])]
            tables += [(t, s) for s in d.get("senses", []) for t in s.get("translations", [])]
            for t, s in tables:
                word = clean_pashto(t.get("word", "")) if t.get("code") == "ps" else ""
                if not word or word in kept or not PASHTO_WORD_RE.match(word):
                    continue
                sense = t.get("sense") or (s.get("glosses") or [None])[-1] if s else t.get("sense")
                gloss = d["word"] + (f" ({sense})" if sense else "")
                if gloss not in entries[word][d.get("pos") or "unknown"]:
                    entries[word][d.get("pos") or "unknown"].append(gloss)
    return entries


def pashto_hand(db, next_id, inflected):
    """
    Adds frequency_pashto's hand-glossed words with their forms, and the regular forms (nominal_forms) of each noun and adjective,
    which most tables lack (ژبه's gives ژبې, not ژبو), but those spelled as an entry is (سره "with" is no form of سر); returns
    the entries added and the next id.
    """
    rows, forms = [], []
    for word, pos, gloss, made in hand_entries():
        rows.append((next_id, word, lowercase(word, "ps"), pos, None, json.dumps([{"glosses": [gloss]}], ensure_ascii=False, separators=(",", ":"))))
        next_id += 1
        forms += [(lowercase(form, "ps"), word, 0) for form in made]
        if made:
            inflected.add((pos, word))
    db.executemany("INSERT INTO entries(id, word, word_lc, pos, ipa, senses) VALUES (?, ?, ?, ?, ?, ?)", rows)
    db.executemany("INSERT OR IGNORE INTO forms(form_lc, lemma, generated) VALUES (?, ?, ?)", forms)
    db.executemany("INSERT OR IGNORE INTO forms(form_lc, lemma, generated) VALUES (?, ?, 0)", [(lowercase(form, "ps"), word) for form, word in more_forms()])
    entries = {w for (w,) in db.execute("SELECT word_lc FROM entries")}
    made = [(lowercase(form, "ps"), word, 1) for word, pos in db.execute("SELECT word, pos FROM entries WHERE pos IN ('noun', 'adj', 'det', 'num', 'pron')")
            for form in nominal_forms(word, pos) if lowercase(form, "ps") not in entries]
    db.executemany("INSERT OR IGNORE INTO forms(form_lc, lemma, generated) VALUES (?, ?, ?)", made)
    return len(rows), next_id


# A Pashto word of the translation tables: its letters alone, one word.
PASHTO_WORD_RE = re.compile("^[\u0621-\u063a\u0641-\u064a\u0679-\u06d3]+$")


# Swahili: the English Wiktionary names a verb with its hyphen ("passive of -penda"), and writes many forms as prose senses
# only, linked to its noun-class appendix ("m class (I) inflected form of -zuri", "... positive degree present of -wako
# (“he/she is (around there)”)"): those are forms of the word named, without the hyphen.
SWAHILI_PROSE_FORM = re.compile(r"\[\[Appendix:Swahili.*\bof (-?[a-z]+(?: na)?)(?: \(“[^”]*”\))?(?:;.*)?$")


# Hausa senses that only name the word they are a form or a spelling of.
HAUSA_PROSE_FORM = re.compile(r"^(possessed form|Niger standard spelling) of (\S+)$")


def swahili_plain_gloss(gloss):
    """The noun-class links as their text: "[[Appendix:Swahili noun classes#N class|n class_((IX))]]" is "n class (IX)"."""
    return re.sub(r"\[\[[^|\]]*\|([^\]]*)\]\]", r"\1", gloss).replace("_((", " (").replace("))", ")")


def swahili_lemma(word):
    return word[1:] if len(word) > 1 and word.startswith("-") and not word.endswith("-") else word


# Yoruba: the English Wiktionary titles an entry without its tones (ọkọ) and gives the toned word as its canonical form
# (ọkọ̀ "vehicle", ọkọ́ "hoe"); a word without one is all mid tones (oko "farm"). An entry is filed under its toned word, a
# second canonical form (bàbà, bábá) is a spelling of it, and its toneless and dotless spellings are generated forms of it
# (yoruba_spellings), found by a lookup only when no entry has that spelling. An Ekiti form of a word ("ò", Ekiti for wò
# "look") is no spelling of the standard language, where it is another word.
def yoruba_heads(d):
    """The toned spellings of an entry, its word first."""
    title = yoruba_standard(d.get("word", "").strip())
    canonical = [yoruba_standard(x["form"].strip()) for x in d.get("forms", []) if "canonical" in (x.get("tags") or []) and x.get("form")]
    heads = [c for c in canonical if toneless(c).lower() == toneless(title).lower()]
    # A second canonical form without tones (rì, ri) is the toneless spelling, generated with the others.
    heads = [c for i, c in enumerate(heads) if i == 0 or toneless(c) != c]
    return list(dict.fromkeys(heads)) or [title]


def yoruba_spellings(word):
    """The spellings of [word] typed without its tones, its dots or both."""
    lc = word.lower()
    return sorted({toneless(lc), dotless(lc), bare(lc)} - {lc})


def lowercase(word, source):
    """Turkish and Azerbaijani have a dotted and a dotless i, so "I" lowers to "ı" and "İ" to "i"; the app does the same."""
    if source in ("tr", "az"):
        word = word.replace("I", "ı").replace("İ", "i")
    # Pashto words are matched with their spellings of one letter folded together (frequency_pashto), and written as spelled.
    if source == "ps":
        return pashto_fold(word)
    return word.lower()


def open_text(path):
    if path.endswith(".gz"):
        return gzip.open(path, "rt", encoding="utf-8")
    return open(path, encoding="utf-8")


def load_glossary(path, variant_re, clean=lambda word: word):
    """
    Returns (entries, forms, variants, dropped) from a Russian or German Wiktionary section. A
    sense that only says "form of X" or "variant of X" becomes a pointer to X rather than a
    gloss, so the app shows X's meaning and links the term to it; entries left without glosses
    are dropped.
    """
    entries = []
    forms = set()
    variants = set()
    dropped = 0
    with open_text(path) as f:
        for line in f:
            d = json.loads(line)
            senses = []
            entry_is_form = "form-of" in d.get("tags", [])
            for s in d.get("senses", []):
                glosses = [g.strip() for g in s.get("glosses", []) if g.strip()]
                # Targets may carry a page anchor such as "log#(глагол_I)".
                form_of = [x["word"].split("#")[0] for x in s.get("form_of", []) if x.get("word")]
                # Nested senses put the description first ("plural de muchacho", "rapazes, jovens").
                described = glosses and FORM_DESCRIPTION_RE.match(glosses[0])
                if not form_of and glosses and (entry_is_form or "form-of" in s.get("tags", []) or described):
                    # The Spanish and Portuguese Wiktionaries often describe a form in prose that
                    # ends with the lemma: "Tercera persona del singular ... del verbo (to) house."
                    match = PROSE_FORM_RE.search(glosses[0])
                    form_of = [match.group(1)] if match else []
                    if not form_of:
                        continue
                for lemma in form_of:
                    if is_clean_form(d["word"], lemma):
                        forms.add((d["word"], lemma))
                if form_of or not glosses:
                    continue
                match = variant_re.match(glosses[0]) if len(glosses) == 1 else None
                if match:
                    variants.add((d["word"], match.group(1)))
                    continue
                sense = {"glosses": glosses}
                tags = s.get("tags", [])
                if tags:
                    sense["tags"] = tags
                examples = examples_of(s)
                if examples:
                    sense["examples"] = examples
                senses.append(sense)
            if not senses:
                dropped += 1
                continue
            entry = {"word": d["word"], "pos": d["pos"], "senses": senses}
            ipa = next((x["ipa"] for x in d.get("sounds", []) if x.get("ipa")), None)
            if ipa:
                entry["ipa"] = ipa
            entries.append(entry)
            for x in d.get("forms", []):
                form = clean(x.get("form", "").strip())
                # Inflection templates sometimes leave only the suffix here ("ed", "ing", "ping"), so a
                # form must share the lemma's stem; irregulars such as "went" come from the English dump.
                stem = plain(d["word"])[: min(3, len(d["word"]) - 1)]
                if is_clean_form(form, d["word"]) and plain(form).startswith(stem):
                    forms.add((form, d["word"]))
    return entries, forms, variants, dropped


def skipped_form(x, skip_tags):
    """Whether a form of the English dump is left out: table markup, an auxiliary, a word torn from a compound tense."""
    tags = set(x.get("tags", []))
    return bool(tags & skip_tags) or (COMPOUND_TENSE_TAG in tags and " " not in x.get("form", "").strip())


def load_english_forms(path, lemmas, spellings=lambda word: [word], skip_tags=SKIP_FORM_TAGS, report_every=200_000):
    """
    Collects (form, lemma) pairs from the English Wiktionary dump for the given lemmas.
    [spellings] lists the spellings a word may be stored under; a headword matches a lemma
    under any of them, and its forms are recorded under all of theirs.
    """
    forms = set()
    seen = 0
    with open_text(path) as f:
        for line in f:
            seen += 1
            if seen % report_every == 0:
                print(f"  scanned {seen:,} English entries, {len(forms):,} forms so far", file=sys.stderr)
            d = json.loads(line)
            raw_word = d.get("word", "")
            for word in spellings(raw_word):
                if word not in lemmas:
                    continue
                for x in d.get("forms", []):
                    if skipped_form(x, skip_tags):
                        continue
                    for form in spellings(x.get("form", "").strip()):
                        if is_clean_form(form, word):
                            forms.add((form, word))
            for s in d.get("senses", []):
                for x in s.get("form_of", []):
                    for lemma in spellings(x.get("word", "")):
                        if lemma not in lemmas:
                            continue
                        for word in spellings(raw_word):
                            if is_clean_form(word, lemma):
                                forms.add((word, lemma))
    return forms


def double_final(word):
    """Doubles the last consonant of a short consonant-vowel-consonant word (stop, stopped)."""
    if len(word) < 3:
        return False
    a, b, c = word[-3], word[-2], word[-1]
    return c not in VOWELS and c not in "wxy" and b in VOWELS and a not in VOWELS


def regular_forms(word, pos):
    """Regular inflections for a single lowercase word; comparatives are too irregular to guess."""
    if len(word) < 2 or not WORD_RE.match(word) or not word.islower() or "'" in word:
        return []
    out = []
    if pos in ("noun", "verb"):
        if word.endswith(("s", "x", "z", "ch", "sh")):
            out.append(word + "es")
        elif word.endswith("y") and word[-2] not in VOWELS:
            out.append(word[:-1] + "ies")
        else:
            out.append(word + "s")
    if pos == "verb":
        if word.endswith("ie"):
            out.append(word[:-2] + "ying")
        elif word.endswith("e") and not word.endswith(("ee", "ye", "oe")):
            out.append(word[:-1] + "ing")
        elif double_final(word):
            out.append(word + word[-1] + "ing")
        else:
            out.append(word + "ing")
        if word.endswith("e"):
            out.append(word + "d")
        elif word.endswith("y") and word[-2] not in VOWELS:
            out.append(word[:-1] + "ied")
        elif double_final(word):
            out.append(word + word[-1] + "ed")
        else:
            out.append(word + "ed")
    return out


