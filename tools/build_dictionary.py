FREQUENCY_DIR = os.path.join(os.path.dirname(TOOLS_DIR), "feature/frequency/src/commonMain/composeResources/files/frequency")


def supplement_path(source, target):
    return os.path.join(GLOSSES_DIR, f"{source}-{target}.tsv")


def read_supplement(path):
    """The (line number, word, pos, senses, field count) rows of a supplement file; senses are the gloss split at SENSE_SEPARATOR."""
    rows = []
    with open(path, encoding="utf-8") as f:
        for number, line in enumerate(f, 1):
            line = line.rstrip("\n").rstrip("\r")
            if not line.strip() or line.startswith("#"):
                continue
            fields = line.split("\t")
            word, pos, gloss = (fields + ["", ""])[:3]
            senses = [s.strip() for s in gloss.split(SENSE_SEPARATOR)]
            rows.append((number, unicodedata.normalize("NFC", word.strip()), pos.strip(), senses, len(fields)))
    return rows


def frequency_list(source, path=None):
    """The app's frequency list for [source] in rank order: (word, its corpus forms); empty when there is none."""
    path = path or os.path.join(FREQUENCY_DIR, f"{source}.tsv")
    if not os.path.exists(path):
        return []
    out = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if not line or line.startswith("#"):
                continue
            word, _, forms = line.partition("\t")
            out.append((word, forms.split(" ") if forms else []))
    return out


def add_supplement(db, source, target):
    """
    Adds an entry for every row of the pack's supplement file whose word has no entry yet, after all
    the others (the last supplement_entries ids), and points the word's corpus forms in the frequency
    list at it where no entry or form row has them; returns (entries, forms) added. Without the file
    nothing changes.
    """
    path = supplement_path(source, target)
    if not os.path.exists(path):
        return 0, 0
    have = {w for (w,) in db.execute("SELECT word_lc FROM entries")}
    next_id = (db.execute("SELECT max(id) FROM entries").fetchone()[0] or 0) + 1
    entry_rows, added = [], set()
    for _, word, pos, senses, _ in read_supplement(path):
        word_lc = lowercase(word, source)
        senses = [s for s in senses if s]
        if not word or not senses or word_lc in have or (word_lc, pos) in added:
            continue
        added.add((word_lc, pos))
        entry_rows.append((next_id, word, word_lc, pos, None, json.dumps([{"glosses": [s]} for s in senses], ensure_ascii=False, separators=(",", ":"))))
        next_id += 1
    db.executemany("INSERT INTO entries(id, word, word_lc, pos, ipa, senses) VALUES (?, ?, ?, ?, ?, ?)", entry_rows)
    words = {lowercase(word, source): word for _, word, _, _, _, _ in entry_rows}
    taken = have | set(words) | {f for (f,) in db.execute("SELECT DISTINCT form_lc FROM forms")}
    form_rows = []
    for word, forms in frequency_list(source):
        lemma = words.get(lowercase(word, source))
        for form in forms if lemma else []:
            form_lc = lowercase(form, source)
            if form_lc and form_lc not in taken:
                taken.add(form_lc)
                form_rows.append((form_lc, lemma))
    db.executemany("INSERT INTO forms(form_lc, lemma, generated) VALUES (?, ?, 1)", form_rows)
    print(f"  {len(entry_rows):,} entries and {len(form_rows):,} forms from {os.path.relpath(path)}", file=sys.stderr)
    return len(entry_rows), len(form_rows)


def finish_output(db, path, out_path, source, target, entry_count, form_count, sources):
    supplement_entries, supplement_forms = add_supplement(db, source, target)
    entry_count += supplement_entries
    form_count += supplement_forms
    form_count -= drop_shared_forms(db, source)
    supplement = [("supplement_entries", str(supplement_entries)), ("supplement_forms", str(supplement_forms))] if supplement_entries else []
    if supplement_entries:
        sources += "; hand-written glosses for frequency-list words (tools/glosses)"
    db.executemany(
        "INSERT INTO meta(key, value) VALUES (?, ?)",
        [
            ("format", str(FORMAT)),
            ("source_language", source),
            ("target_language", target),
            ("entry_count", str(entry_count)),
            ("form_count", str(form_count)),
            ("sources", sources),
            ("license", "CC BY-SA 4.0"),
        ] + supplement,
    )
    db.executescript(
        f"""
        CREATE INDEX IF NOT EXISTS entries_word_lc ON entries(word_lc);
        CREATE INDEX IF NOT EXISTS forms_form_lc ON forms(form_lc);
        PRAGMA user_version = {FORMAT};
        """
    )
    db.commit()
    db.execute("VACUUM")
    db.close()
    with open(path, "rb") as plain, gzip.open(out_path, "wb", compresslevel=9) as packed:
        shutil.copyfileobj(plain, packed)


def write_sqlite(out_path, entries, form_rows, source, target):
    db, path = open_output(out_path)
    db.executemany(
        "INSERT INTO entries(id, word, word_lc, pos, ipa, senses) VALUES (?, ?, ?, ?, ?, ?)",
        (
            (i + 1, e["word"], lowercase(e["word"], source), e["pos"], e.get("ipa"), json.dumps(e["senses"], ensure_ascii=False, separators=(",", ":")))
            for i, e in enumerate(entries)
        ),
    )
    db.executemany("INSERT INTO forms(form_lc, lemma, generated) VALUES (?, ?, ?)", ((f, l, 1 if g else 0) for f, l, g in form_rows))
    finish_output(
        db, path, out_path, source, target, len(entries), len(form_rows),
        f"{TARGETS[target][0]} via kaikki.org (glosses); English Wiktionary {SOURCES[source][0]} entries via kaikki.org (inflections)",
    )


# Example sentences kept per sense; quotations from literature are left out, they are long and dated.
MAX_EXAMPLES = 3


def examples_of(sense):
    """A sense's example sentences with their translations, as the app reads them: [{"text", "translation"}]."""
    out = []
    for x in sense.get("examples", []):
        text = " ".join((x.get("text") or "").split())
        if not text or x.get("type") == "quotation" or len(text) > 300:
            continue
        example = {"text": text}
        translation = " ".join((x.get("translation") or x.get("english") or "").split())
        if translation:
            example["translation"] = translation
        out.append(example)
        if len(out) == MAX_EXAMPLES:
            break
    return out


# Sense tags that only repeat the part of speech or table markup rather than describe usage.
NOISE_SENSE_TAGS = {"form-of", "alt-of", "no-gloss", "morpheme", "romanization"}


# The English Wiktionary's Urdu entries miss many everyday words (تک, رکھنا, دوران, یہی); its Hindi entries name their
# Urdu spelling, and Hindi and Urdu share their words.
HINDI_DUMP = "dictionaries/kaikki.org-dictionary-Hindi.jsonl.gz"


def urdu_gender(d):
    """masculine or feminine, from an entry's canonical form or head; None when it has neither or both."""
    tags = set(d.get("tags", []))
    for x in d.get("forms", []):
        if "canonical" in (x.get("tags") or []):
            tags |= set(x["tags"])
    for h in d.get("head_templates", []):
        g = str(h.get("args", {}).get("g", ""))
        tags |= {"masculine"} if g.startswith("m") else {"feminine"} if g.startswith("f") else set()
    genders = tags & {"masculine", "feminine"}
    return next(iter(genders)) if len(genders) == 1 else None


def urdu_from_hindi(kept, next_id):
    """
    Entries for the Urdu spellings of the Hindi entries (तक's تک) that no Urdu entry of the same part of speech has, glossed
    as the Hindi entry is (its own senses, without its Devanagari examples), with their urdu_kept rows; and the next id.
    """
    have = {(word, pos) for word, pos, _, _ in kept}
    added = []
    with open_text(HINDI_DUMP) as f:
        for line in f:
            d = json.loads(line)
            spellings = [urdu_fold(x["form"].strip()) for x in d.get("forms", []) if "Urdu" in (x.get("tags") or [])]
            pos = d.get("pos") or "unknown"
            spellings = [w for w in dict.fromkeys(spellings) if w and (w, pos) not in have and WORD_RE.match(w.replace(" ", ""))]
            if not spellings:
                continue
            senses = []
            for s in d.get("senses", []):
                tags = s.get("tags", [])
                if s.get("form_of") or s.get("alt_of") or "form-of" in tags or "alt-of" in tags:
                    continue
                glosses = [g.strip() for g in s.get("glosses", []) if g.strip()]
                if not glosses:
                    continue
                sense = {"glosses": [glosses[-1]]}
                kept_tags = [t for t in tags if t not in NOISE_SENSE_TAGS]
                if kept_tags:
                    sense["tags"] = kept_tags
                senses.append(sense)
            if not senses:
                continue
            # A Hindi adjective's table names its feminine (अच्छी) when it inflects.
            inflects = pos == "adj" and any("feminine" in (x.get("tags") or []) for x in d.get("forms", []))
            for word in spellings:
                have.add((word, pos))
                row = (next_id, word, lowercase(word, "ur"), pos, None, json.dumps(senses, ensure_ascii=False, separators=(",", ":")))
                added.append((row, (word, pos, urdu_gender(d), inflects or pos == "noun")))
                next_id += 1
    return added, next_id


# The English Wiktionary has about 1,700 Hausa words and misses the commonest (na, ne, kuma, za, akwai); Wikidata's Hausa lexemes
# (CC0, dictionaries/wikidata-ha-lexemes.tsv and wikidata-ha-forms.tsv, from its query service) add 1,100 more, and the English
# entries' translation tables some more. Their Ajami (ha-arab) spellings are left out.
HAUSA_LEXEMES = "dictionaries/wikidata-ha-lexemes.tsv"
HAUSA_LEXEME_FORMS = "dictionaries/wikidata-ha-forms.tsv"
HAUSA_POS = {"noun": "noun", "verb": "verb", "adjective": "adj", "adverb": "adv", "preposition": "prep", "interjection": "intj",
             "numeral": "num", "proper noun": "name", "proverb": "proverb", "suffix": "suffix", "linker": "particle",
             "determiner": "det", "demonstrative determiner": "det", "interrogative determinant": "det", "conjunction": "conj",
             "coordinating conjunction": "conj", "subordinating conjunction": "conj", "complementizer": "conj",
             "demonstrative adverb": "adv", "interrogative adverb": "adv", "verbal locution": "phrase", "pronominal locution": "phrase",
             "nominal": "noun"}
# A Wikidata form that is the lexeme's own: its plural, an adjective's feminine, a verb's form before an object or a pronoun,
# another spelling. Its synonyms, verbal nouns and a noun's other gender are words of their own.
HAUSA_FORM_FEATURES = {"plural", "direct object clause", "pronominal verb", "indirect object clause"}


def _wikidata_text(cell):
    m = re.fullmatch(r'"(.*)"(?:@([a-z-]+))?', cell.strip())
    return (m.group(1).replace('\\"', '"'), m.group(2)) if m else (None, None)


def hausa_lexemes():
    """Wikidata's Hausa lexemes in Latin letters: (word, pos, glosses, forms)."""
    lexemes = {}
    with open(HAUSA_LEXEMES, encoding="utf-8") as f:
        next(f)
        for line in f:
            uri, lemma, category, glosses = (line.rstrip("\n").split("\t") + ["", "", "", ""])[:4]
            word, script = _wikidata_text(lemma)
            if not word or script not in ("ha", "ha-ne") or AJAMI.search(word):
                continue
            category = _wikidata_text(category)[0] or ""
            pos = HAUSA_POS.get(category, "pron" if "pronoun" in category else "particle" if "particle" in category else category)
            text = _wikidata_text(glosses)[0] or ""
            senses = [g.strip() for g in text.split(" | ") if g.strip()]
            lexemes[uri] = (hausa_clean(word), pos, senses, set())
    with open(HAUSA_LEXEME_FORMS, encoding="utf-8") as f:
        next(f)
        for line in f:
            uri, _, rep, features = (line.rstrip("\n").split("\t") + ["", "", "", ""])[:4]
            form = _wikidata_text(rep)[0]
            features = set((_wikidata_text(features)[0] or "").split(","))
            if uri not in lexemes or not form or AJAMI.search(form):
                continue
            word, pos, _, forms = lexemes[uri]
            if features & HAUSA_FORM_FEATURES or features <= {"singular", ""} or pos == "adj" and "feminine" in features:
                forms.add(hausa_clean(form))
    return list(lexemes.values())


def hausa_translation_entries():
    """The Hausa words of the English entries' translation tables, by part of speech: word -> pos -> English glosses."""
    entries = defaultdict(lambda: defaultdict(list))
    with open_text(SOURCES["en"][2]) as f:
        for line in f:
            if '"code": "ha"' not in line:
                continue
            d = json.loads(line)
            for t in d.get("translations", []):
                if t.get("code") != "ha":
                    continue
                word = hausa_clean(t.get("word", ""))
                if not word or AJAMI.search(word) or not WORD_RE.match(word.replace(" ", "")):
                    continue
                gloss = d["word"] + (f" ({t['sense']})" if t.get("sense") else "")
                if gloss not in entries[word][d.get("pos") or "unknown"]:
                    entries[word][d.get("pos") or "unknown"].append(gloss)
    return entries


def urdu_generated(kept):
    """
    (form, word) rows by frequency_urdu's rules: every verb's, a noun's whose table gave none, and an adjective's that the
    Hindi entry's table shows inflected (an Urdu entry's that inflects has its table).
    """
    rows = []
    for word, pos, gender, by_rule in kept:
        if pos == "verb":
            forms = verb_forms(word)
        elif pos == "adj" and by_rule:
            forms = adjective_forms(word)
        elif pos == "noun" and by_rule:
            forms = noun_forms(word, gender)
        else:
            forms = []
        rows += [(lowercase(form, "ur"), word) for form in forms]
    return rows


def nepali_generated(kept, inflected):
    """
    (form, word) rows for Nepali: the pronouns' forms (frequency_nepali.PRONOUNS, as the pack's tables list every pronoun on each
    one's page), and a noun's, adjective's or number's plural and postpositions written on (घरहरू, घरमा) when it has no table.
    """
    words = {word for word, _ in kept}
    rows = [(form, word) for word, forms in frequency_nepali.PRONOUNS.items() if word in words for form in forms.split()]
    for word, pos in kept:
        if pos in ("noun", "adj", "num") and (pos, word) not in inflected and len(word) > 1:
            rows += [(form, word) for form in frequency_nepali.pack_forms(word, {pos})]
    return rows


def build_english_target(source, en_path, out_path, report_every=200_000):
    """
    Builds a pack whose glosses are the English Wiktionary's own definitions. Entries and forms
    stream straight into SQLite, since the larger dumps hold millions of forms.
    """
    cleaner = CLEANERS.get(source, lambda word: word)
    skip_tags = SKIP_FORM_TAGS | SKIP_FORM_TAGS_BY_SOURCE.get(source, set())
    # Croatian is written in Latin letters; Malay too, its Jawi spellings (forms and entries of their own) left out; and
    # Azerbaijani (since 1991), not in the Cyrillic before it nor the Arabic alphabet of Iran's South Azerbaijani; and Uzbek
    # (since 1993), not in the Cyrillic many still write it in nor the Arabic alphabet before that.
    latin_only = source in ("hr", "ms", "az", "ha", "uz")
    db, path = open_output(out_path)
    db.execute("CREATE UNIQUE INDEX forms_unique ON forms(form_lc, lemma)")
    entry_rows, form_rows, seen, next_id = [], [], 0, 1
    entry_count = form_count = pointer_count = 0
    pos_totals, pos_inflected = Counter(), set()
    # Urdu's entries as (word, pos, gender, whether its forms are made by rule), for urdu_generated.
    urdu_kept = []
    # Nepali's as (word, pos), for nepali_generated.
    nepali_kept = []

    def flush():
        nonlocal entry_rows, form_rows, form_count
        db.executemany("INSERT INTO entries(id, word, word_lc, pos, ipa, senses) VALUES (?, ?, ?, ?, ?, ?)", entry_rows)
        before = db.total_changes
        db.executemany("INSERT OR IGNORE INTO forms(form_lc, lemma, generated) VALUES (?, ?, 0)", form_rows)
        form_count += db.total_changes - before
        entry_rows, form_rows = [], []

    def cyrillic(text):
        return any("\u0400" <= c <= "\u04ff" for c in text)

    def jawi(text):
        return any("\u0600" <= c <= "\u06ff" or "\u0750" <= c <= "\u077f" for c in text)

    foreign = jawi if source == "ms" else (lambda text: cyrillic(text) or jawi(text)) if source in ("az", "uz") else cyrillic
    # Punjabi is read in Gurmukhi; its Shahmukhi spellings (forms and entries of their own) are left out.
    if source == "pa":
        latin_only, foreign = True, jawi
    punjabi_vocative, punjabi_other = set(), set()
    if source == "ha":
        foreign = AJAMI.search

    print(f"Reading {en_path}", file=sys.stderr)
    with open_text(en_path) as f:
        for line in f:
            seen += 1
            if seen % report_every == 0:
                print(f"  scanned {seen:,} entries, kept {entry_count:,} with {form_count + len(form_rows):,} forms", file=sys.stderr)
            d = json.loads(line)
            word = cleaner(d.get("word", "").strip())
            if source == "yo":
                word, *variants = yoruba_heads(d)
            if not word or (latin_only and foreign(word)):
                continue
            senses = []
            for s in d.get("senses", []):
                tags = s.get("tags", [])
                if source == "yo" and "Ekiti" in tags and (s.get("form_of") or s.get("alt_of")):
                    continue
                targets = [cleaner(x["word"]) for x in s.get("form_of", []) + s.get("alt_of", []) if x.get("word")]
                if source == "sw":
                    prose = [m.group(1) for g in s.get("glosses", [])[-1:] if (m := SWAHILI_PROSE_FORM.search(g))]
                    # A form of the one-letter -a ("of": ya, za, vya) stays an entry, as the pack keeps no one-letter lemma.
                    targets = [t for t in (swahili_lemma(t) for t in targets or prose) if len(t) > 1]
                if source == "ha" and not targets:
                    # "possessed form of sātā̀" (satar), and "Niger standard spelling of 'ya", which is the same word folded.
                    targets = [cleaner(m.group(2)) for g in s.get("glosses", [])[-1:] if (m := HAUSA_PROSE_FORM.match(g))]
                if source == "ha":
                    # A form of two words names them together ("plural of ɗan and 'ya").
                    targets = [t for target in targets for t in target.split(" and ")]
                for lemma in targets:
                    if is_clean_form(word, lemma, source) and not (latin_only and foreign(lemma)):
                        form_rows.append((lowercase(word, source), lemma))
                        pointer_count += 1
                if targets or "form-of" in tags or "alt-of" in tags:
                    continue
                glosses = [g.strip() for g in s.get("glosses", []) if g.strip()]
                if not glosses:
                    continue
                if source == "sw":
                    glosses = [swahili_plain_gloss(g) for g in glosses]
                # Nested senses list their parent gloss first; the last entry is the sense itself.
                sense = {"glosses": [glosses[-1]]}
                kept_tags = [t for t in tags if t not in NOISE_SENSE_TAGS]
                if kept_tags:
                    sense["tags"] = kept_tags
                examples = examples_of(s)
                if examples:
                    sense["examples"] = examples
                senses.append(sense)
            if not senses:
                continue
            pos = d.get("pos") or "unknown"
            ipa = next((x["ipa"] for x in d.get("sounds", []) if x.get("ipa")), None)
            entry_rows.append((next_id, word, lowercase(word, source), pos, ipa, json.dumps(senses, ensure_ascii=False, separators=(",", ":"))))
            next_id += 1
            entry_count += 1
            pos_totals[pos] += 1
            stem = plain(word)[: min(3, len(word) - 1)]
            for x in d.get("forms", []):
                if skipped_form(x, skip_tags) or other_pronoun_form(source, word, x):
                    continue
                # Urdu verb tables name their persons' pronouns (میں, تم, آپ) beside the forms, untagged or with the person's tags.
                if source == "ur" and (not x.get("tags") or pos == "verb" and cleaner(x.get("form", "").strip()) in TABLE_PRONOUNS):
                    continue
                # A Nepali pronoun's table lists every pronoun (म's has हामी, तिमी, यो...): its forms come from frequency_nepali.
                if source == "ne" and pos == "pron":
                    continue
                if source == "mr" and pos == "verb" and cleaner(x.get("form", "").strip()) in MARATHI_TABLE_LABELS:
                    continue
                # A noun names its other gender's word (لڑکی of لڑکا, والدہ of والد), no form of it.
                if source == "ur" and set(x["tags"]) <= {"masculine", "feminine"}:
                    continue
                # So does a Hausa one (yarinya of yaro, saniya of sa), and a pronoun the others of its person (ita, su of shi).
                if source == "ha" and (pos == "noun" and {"masculine", "feminine"} & set(x.get("tags", []))
                                       or pos == "pron" and cleaner(x.get("form", "")) in ("shi", "ita", "su")):
                    continue
                form = cleaner(x.get("form", "").strip())
                # A one-letter word has no forms, but for Azerbaijani's "o" ("he, she, it; that"): onu, ona, onun.
                own = is_clean_form(form, word, source) or (source == "az" and word == "o" and form != word and WORD_RE.match(form))
                if not own or (latin_only and foreign(form)) or (source == "so" and not somali_form(form, word)):
                    continue
                if source == "pa":
                    tags = set(x.get("tags", []))
                    # A Punjabi noun's head gives the noun of the other gender (ਧੀ of ਪੁੱਤਰ), another word.
                    if pos == "noun" and not x.get("source") and tags & {"feminine", "masculine"}:
                        continue
                    (punjabi_vocative if "vocative" in tags else punjabi_other).add((lowercase(form, source), word))
                form_rows.append((lowercase(form, source), word))
                pos_inflected.add((pos, word))
            if source == "ne":
                nepali_kept.append((word, pos))
            if source == "ur":
                urdu_kept.append((word, pos, urdu_gender(d), pos == "noun" and (pos, word) not in pos_inflected))
            if source == "yo":
                form_rows += [(lowercase(v, source), word) for v in variants if lowercase(v, source) != lowercase(word, source)]
            if len(entry_rows) >= 5000 or len(form_rows) >= 50000:
                flush()
    flush()
    label = f"English Wiktionary {SOURCES[source][0]} entries via kaikki.org"
    if source in ("bn", "ta", "te", "ne", "gu", "mr", "am"):
        kept = {w for (w,) in db.execute("SELECT word FROM entries")}
        translated = (bengali_translation_entries(kept) if source == "bn"
                      else bengali_translation_entries(kept, "ta", clean_tamil, TAMIL_WORD_RE) if source == "ta"
                      else bengali_translation_entries(kept, "ne", clean_nepali, NEPALI_WORD_RE) if source == "ne"
                      else bengali_translation_entries(kept, "gu", clean_gujarati, GUJARATI_WORD_RE) if source == "gu"
                      else bengali_translation_entries(kept, "mr", clean_marathi, MARATHI_WORD_RE) if source == "mr"
                      else amharic_translation_entries(kept) if source == "am"
                      else telugu_translation_entries(kept))
        for word, by_pos in sorted(translated.items()):
            for pos, glosses in sorted(by_pos.items()):
                senses = [{"glosses": [g]} for g in glosses]
                entry_rows.append((next_id, word, lowercase(word, source), pos, None, json.dumps(senses, ensure_ascii=False, separators=(",", ":"))))
                if source == "ne":
                    nepali_kept.append((word, pos))
                next_id += 1
                entry_count += 1
        flush()
        label += " and its English entries' translation tables"
    if source == "ne":
        before = db.total_changes
        db.executemany("INSERT OR IGNORE INTO forms(form_lc, lemma, generated) VALUES (?, ?, 1)", nepali_generated(nepali_kept, pos_inflected))
